class Command(BaseCommand):
    help = 'Clear all catalog data and seed with 4 real-product categories.'

    def handle(self, *args, **options):
        self.stdout.write(self.style.WARNING('⚠  Clearing existing catalog data...'))
        with transaction.atomic():
            ProductTagGroup.objects.all().delete()
            Tag.objects.all().delete()
            TagName.objects.all().delete()
            ProductFeature.objects.all().delete()
            Feature.objects.all().delete()
            FeatureValue.objects.all().delete()
            Image.objects.all().delete()
            Product.objects.all().delete()
            Category.objects.all().delete()
            Brand.objects.all().delete()
        self.stdout.write(self.style.SUCCESS('✓  Cleared.\n'))

        # Pre-create brands
        brand_map = {}
        brand_names = set()
        for cat_data in CATALOG.values():
            for p in cat_data['products']:
                brand_names.add(p['brand'])
        for bname in brand_names:
            b, _ = Brand.objects.get_or_create(name=bname)
            brand_map[bname] = b
        self.stdout.write(self.style.SUCCESS(f'✓  Created {len(brand_map)} brands.'))

        total_products = 0

        for cat_slug, cat_data in CATALOG.items():
            self.stdout.write(f'\n📁  Category: {cat_data["name"]}')
            cat = Category.objects.create(
                name=cat_data['name'],
                slug=cat_slug,
                order=cat_data['order'],
            )

            # ── Tag shelves ──────────────────────────────────────
            shelf_map = {}  # shelf_name -> (TagName, [Tag, …])
            for shelf_name, tag_names in cat_data['tag_shelves']:
                tn, tags = create_tag_shelf(cat, shelf_name, tag_names)
                shelf_map[shelf_name] = (tn, tags)
                tag_map = {t.name: t for t in tags}
                shelf_map[shelf_name] = (tn, tag_map)
            self.stdout.write(f'  ✓ {len(shelf_map)} tag shelves created.')

            # ── Products ─────────────────────────────────────────
            for idx, pdata in enumerate(cat_data['products']):
                self.stdout.write(f'  [{idx+1}/10] {pdata["name"]}', ending=' ')

                product = Product.objects.create(
                    name=pdata['name'],
                    brand=brand_map[pdata['brand']],
                    category=cat,
                    price=pdata['price'],
                    description=pdata['description'],
                    manufacturer_sku=pdata['sku'],
                    is_available=True,
                )

                # Features (20 per product)
                for feat_name, feat_val in pdata['features']:
                    f = get_or_create_feature(feat_name, cat)
                    attach_feature(product, f, feat_val)

                # Images
                for img_idx, img_url in enumerate(pdata['images']):
                    create_product_image(
                        product, img_url,
                        is_main=(img_idx == 0),
                        order=img_idx,
                    )

                # Tags
                for shelf_name, tag_names in pdata['tags'].items():
                    if shelf_name not in shelf_map:
                        continue
                    tn, tag_map = shelf_map[shelf_name]
                    selected_tags = [tag_map[t] for t in tag_names if t in tag_map]
                    if selected_tags:
                        attach_tags(product, tn, selected_tags)

                total_products += 1
                self.stdout.write(self.style.SUCCESS('✓'))

        self.stdout.write(
            self.style.SUCCESS(
                f'\n🎉  Done! Created 4 categories, {total_products} products.'
            )
        )
